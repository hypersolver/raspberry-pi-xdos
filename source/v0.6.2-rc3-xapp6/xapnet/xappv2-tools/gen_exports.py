#!/usr/bin/env python3
"""Generate the kernel export table for kernel-independent XAPP V2 modules (R17).

    gen_exports.py kernel8-32.elf xdos_exports.c [--abi N]

Reads every global/weak defined FUNC or OBJECT symbol of a first-pass kernel link
and writes a C file with `xdos_exports` (FNV-1a hash -> address, sorted by hash)
and `xdos_export_count`, plus the ABI gate symbol `__xdos_abi_<N>`. Relink the
kernel with this file: the table references every symbol by relocation, so the
addresses are those of the final link (Thumb functions keep bit 0) and none of
them can be dropped by --gc-sections. Hash collisions between different names
stop the build.
"""
import argparse
import sys
from pathlib import Path

from elftools.elf.elffile import ELFFile


def fnv1a(name):
    h = 2166136261
    for b in name.encode():
        h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return h


def keep_file(listing, out):
    """First-link helper: reference every ABI name so the linker keeps it (a name the
    kernel no longer defines fails the link as an undefined reference)."""
    names = sorted({l.strip() for l in Path(listing).read_text().splitlines()
                    if l.strip() and not l.startswith("#")})
    lines = ["/* Generated by gen_exports.py --keep: keeps the XAPP ABI export list linked. */"]
    lines += [f'extern char xdos_keep_{i} __asm__("{n}");' for i, n in enumerate(names)]
    lines.append("const void *const xdos_abi_keep[] __attribute__((used)) = {")
    lines += [f"    &xdos_keep_{i}," for i in range(len(names))]
    lines.append("};")
    Path(out).write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"gen_exports: keeping {len(names)} ABI names")


def main():
    if len(sys.argv) == 4 and sys.argv[1] == "--keep":
        keep_file(sys.argv[2], sys.argv[3])
        return
    ap = argparse.ArgumentParser()
    ap.add_argument("elf")
    ap.add_argument("out")
    ap.add_argument("--abi", type=int, default=1)
    ap.add_argument("--require", help="ABI export list (abi-exports.txt): every name must be exported")
    a = ap.parse_args()
    gate = f"__xdos_abi_{a.abi}"
    names = set()
    with open(a.elf, "rb") as f:
        for sym in ELFFile(f).get_section_by_name(".symtab").iter_symbols():
            info = sym["st_info"]
            if (info["bind"] in ("STB_GLOBAL", "STB_WEAK") and info["type"] in ("STT_FUNC", "STT_OBJECT")
                    and sym["st_shndx"] != "SHN_UNDEF" and sym.name
                    and not sym.name.startswith("xdos_export")
                    and not sym.name.startswith("__xdos_abi_")
                    and not sym.name.startswith("xdos_abi_keep")):
                names.add(sym.name)
    if a.require:
        wanted = {l.strip() for l in Path(a.require).read_text().splitlines()
                  if l.strip() and not l.startswith("#")}
        missing = sorted(wanted - names)
        if missing:
            sys.exit(f"gen_exports: kernel lost {len(missing)} ABI exports, e.g. {missing[:8]} "
                     "(keep them or bump the ABI)")
    names.add(gate)
    table = {}
    for name in sorted(names):
        h = fnv1a(name)
        if h in table:
            sys.exit(f"gen_exports: hash collision {table[h]} / {name}")
        table[h] = name
    lines = ["/* Generated by gen_exports.py: kernel export table for XAPP V2 imports (R17). */",
             "#include <stdint.h>",
             "typedef struct { uint32_t hash; const void *addr; } XdosExportEntry;",
             f"const char {gate} = {a.abi};"]
    order = sorted(table)
    for i, h in enumerate(order):
        if table[h] != gate:
            lines.append(f'extern char xdos_export_{i} __asm__("{table[h]}");')
    lines.append("const XdosExportEntry xdos_exports[] = {")
    for i, h in enumerate(order):
        target = gate if table[h] == gate else f"xdos_export_{i}"
        lines.append(f"    {{0x{h:08x}u, &{target}}},")
    lines.append("};")
    lines.append(f"const uint32_t xdos_export_count = {len(order)}u;")
    Path(a.out).write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"gen_exports: {len(order)} exports, ABI gate {gate}")


if __name__ == "__main__":
    main()
